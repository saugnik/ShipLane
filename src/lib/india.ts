export type PincodeLookup = {
  pincode: string;
  city: string | null;
  state: IndianState | null;
  /** How confident we are — drives the UI hint shown next to the field. */
  precision: "exact" | "district" | "state" | "unknown";
};

export function isValidPincode(pin: string): boolean {
  return /^[1-9][0-9]{5}$/.test(pin.trim());
}

export function lookupPincode(raw: string): PincodeLookup {
  const pin = raw.trim();
  const base: PincodeLookup = { pincode: pin, city: null, state: null, precision: "unknown" };
  if (!isValidPincode(pin)) return base;

  const exact = PIN6_OVERRIDE[pin];
  if (exact) return { pincode: pin, city: exact[0], state: exact[1], precision: "exact" };

  const district = PIN3_CITY[pin.slice(0, 3)];
  if (district) return { pincode: pin, city: district[0], state: district[1], precision: "district" };

  const state = PIN2_STATE[pin.slice(0, 2)];
  if (state) return { pincode: pin, city: null, state, precision: "state" };

  return base;
}

/**
 * Google (and most third-party address sources) spell the multi-word union
 * territories with "and" and use pre-rename district names. Fold those onto the
 * canonical list so a Places result lands on a value our rate cards recognise.
 */
const STATE_ALIASES: Record<string, IndianState> = {
  "jammu and kashmir": "Jammu & Kashmir",
  "andaman and nicobar islands": "Andaman & Nicobar Islands",
  "andaman and nicobar": "Andaman & Nicobar Islands",
  "dadra and nagar haveli and daman and diu": "Dadra & Nagar Haveli and Daman & Diu",
  "dadra and nagar haveli": "Dadra & Nagar Haveli and Daman & Diu",
  "daman and diu": "Dadra & Nagar Haveli and Daman & Diu",
  "nct of delhi": "Delhi",
  "national capital territory of delhi": "Delhi",
  "new delhi": "Delhi",
  pondicherry: "Puducherry",
  orissa: "Odisha",
  uttaranchal: "Uttarakhand",
  "tamilnadu": "Tamil Nadu",
};

export function normalizeStateName(raw: string | null | undefined): IndianState | null {
  if (!raw) return null;
  const value = raw.trim();
  const exact = INDIAN_STATES.find((s) => s.toLowerCase() === value.toLowerCase());
  if (exact) return exact;

  const key = value.toLowerCase().replace(/\s+/g, " ");
  if (STATE_ALIASES[key]) return STATE_ALIASES[key];

  // "Jammu & Kashmir" vs "Jammu and Kashmir" and stray punctuation.
  const loose = key.replace(/&/g, "and").replace(/[.,]/g, "").trim();
  if (STATE_ALIASES[loose]) return STATE_ALIASES[loose];

  const fuzzy = INDIAN_STATES.find(
    (s) => s.toLowerCase().replace(/&/g, "and").replace(/[.,]/g, "") === loose,
  );
  return fuzzy ?? null;
}


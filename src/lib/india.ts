/** Distinct known cities for a state — powers the rate-card city dropdown. */
export function citiesForState(state: string): string[] {
  const set = new Set<string>();
  for (const [city, st] of Object.values(PIN3_CITY)) if (st === state) set.add(city);
  for (const [city, st] of Object.values(PIN6_OVERRIDE)) if (st === state) set.add(city);
  return [...set].sort((a, b) => a.localeCompare(b));
}

